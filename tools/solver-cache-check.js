#!/usr/bin/env node
/* Full-budget Monte Carlo cache, isolation, eviction, age and storage fallback. */
'use strict';
const assert = require('node:assert/strict');
const C = require('../js/solver-cache.js');
const S = require('../js/solver.js'), T = require('../js/engine.js');
async function main() {
  assert.equal(C.key({ day: 2, cell: { beast: 'rat', tier: 1 } }, 8), C.key({ cell: { tier: 1, beast: 'rat' }, day: 2 }, 8));
  assert.notEqual(C.key({ day: 2 }, 8), C.key({ day: 3 }, 8));
  assert.notEqual(C.key({ day: 2 }, 8), C.key({ day: 2 }, 9));
  assert.notEqual(C.key({ tools: ['rope', 'keys'] }, 8), C.key({ tools: ['keys', 'rope'] }, 8));
  const state = T.newGame({ seed: 'CACHE', params: { rewards: false, drillDays: 2 } });
  const job = S.solve(state, { rollouts: 8, seed: 71 });
  let result;
  do { result = job.step(1000); } while (!result.done);
  assert.ok(result.options.length > 1);
  assert.equal(result.rounds, 8);
  const cache = C.create({ version: 'test', persistent: false, maxEntries: 2 });
  await cache.ready;
  assert.equal(cache.get('A', 8), null);
  assert.equal(cache.put('A', result, 8), true);
  assert.deepEqual(cache.get('A', 8), result);
  const got = cache.get('A', 8);
  got.options[0].mean += 100;
  assert.deepEqual(cache.get('A', 8), result, 'A consumer mutated the cached summary');
  const source = structuredClone(result);
  source.options[0].gapSe = Infinity;
  cache.put('B', source, 8);
  source.options[0].mean += 100;
  assert.equal(cache.get('B', 8).options[0].gapSe, Infinity);
  assert.equal(cache.get('B', 8).options[0].mean, result.options[0].mean);
  assert.equal(cache.get('B', 9), null, 'A different simulation budget reused the result');
  cache.get('A', 8);
  cache.put('C', result, 8);
  assert.equal(cache.get('B', 8), null, 'Eviction did not respect recent use');
  assert.deepEqual(cache.get('A', 8), result);
  assert.deepEqual(cache.get('C', 8), result);
  assert.equal(cache.info().entries, 2);
  assert.equal(cache.info().pending, 0, 'Memory-only evictions accumulated disk mutations');
  assert.equal(cache.put('partial', { ...result, done: false }, 8), false);
  assert.equal(cache.put('reduced', { ...result, rounds: 7 }, 8), false);
  assert.equal(cache.put('bad-goal', { ...result, goal: 'wrong' }, 8), false);
  const invalid = structuredClone(result); invalid.options[0].mean = NaN;
  assert.equal(cache.put('bad-number', invalid, 8), false);
  const circular = { ...result }; circular.extra = circular;
  assert.equal(cache.put('bad-shape', circular, 8), false);
  const one = { ...result, options: result.options.slice(0, 1), rounds: 0 };
  assert.equal(cache.put('forced-move', one, 1600), true);
  assert.deepEqual(cache.get('forced-move', 1600), one);
  const size = C.create({ persistent: false }); size.put('A', result, 8);
  const small = C.create({ persistent: false, maxBytes: size.info().bytes - 1 });
  assert.equal(small.put('A', result, 8), false);
  assert.equal(small.info().entries, 0);
  const byteLimit = C.create({ persistent: false, maxBytes: Math.ceil(size.info().bytes * 1.5) });
  byteLimit.put('A', result, 8); byteLimit.put('B', result, 8);
  assert.equal(byteLimit.info().entries, 1);
  let clock = 1000;
  const expiring = C.create({ persistent: false, ttl: 50, now: () => clock });
  expiring.put('A', result, 8); clock += 49;
  assert.deepEqual(expiring.get('A', 8), result);
  clock += 2;
  assert.equal(expiring.get('A', 8), null, 'Touching an entry extended its maximum age');
  console.log('PASS: full-budget summaries, exact clone isolation, Infinity, budget checks, LRU, byte limits and expiry.');
  try {
    global.indexedDB = { open() { throw new Error('Test: storage unavailable'); } };
    const unavailable = C.create({ version: 'test' });
    await unavailable.ready;
    unavailable.put('A', result, 8);
    assert.deepEqual(unavailable.get('A', 8), result);
    assert.equal(unavailable.info().pending, 0);
    global.indexedDB = { open() { const request = {}; queueMicrotask(() => request.onblocked()); return request; } };
    const blocked = C.create({ version: 'test' });
    blocked.put('A', result, 8);
    await blocked.ready;
    assert.deepEqual(blocked.get('A', 8), result);
    assert.equal(blocked.info().pending, 0);
  } finally { delete global.indexedDB; }
  console.log('PASS: unavailable/blocked persistent storage retains a working bounded memory cache.');
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
